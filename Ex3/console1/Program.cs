//OPERADORES ARITMÉTICOS
class Program
{
    static void Main(string[] args)
    {
        int a = 10;
        int b = 3;

        int sum = a + b; // Sum | Soma
        int difference = a - b; // Subtraction | Subtração
        int product = a * b; // Multiplication | Multiplicação
        int division = a / b; // Division | Divisão
        int modulus = a % b; // Modulus | Módulo

        Console.WriteLine("Number a: " + a);    
        Console.WriteLine("Number b: " + b);
        Console.WriteLine("Sum: " + sum);
        Console.WriteLine("Difference: " + difference);
        Console.WriteLine("Product: " + product);
        Console.WriteLine("Division: " + division);
        Console.WriteLine("Modulus: " + modulus);

    }
}